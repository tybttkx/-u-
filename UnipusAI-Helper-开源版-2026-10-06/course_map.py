# -*- coding: utf-8 -*-
"""课程 id（URL 里的 cid）→ 教材名，用于收割时防止串书。

为什么需要：课件页面的 cid 与教材一一对应，而"教材识别"偶尔会认错书；
只比对教材名挡不住同系列（如《新视野大学英语（第四版）读写教程3》与
《视听说教程3》都含"新视野大学英语（第四版）"）的情况。
"""

import re

#: 获取 cid：浏览器打开课程页，地址栏 ?cid= 后面那串数字（或让「抓页面.py」帮忙看）。
#: 新增课程时补一行即可；没收录的 cid 一律不硬猜、走普通识别。
COURSE_MAP = {
    # 视听说教程3 —— 2026-10-03 实机核对：该 cid 的页面标题就是「新视野大学英语（第四版）视听说教程3」
    # （此前 1579641409030619139 ↔ 1579642886499368960 两本书标反了，
    #   导致视听说3 的页面被认成读写教程3，收割也往错书里写）
    "1579642886499368960": "新视野大学英语 视听说教程3",
    # 读写教程1
    "1855335437114605653": "新视野大学英语 读写教程1",
    # 原「1579641409030619139」条目未能实机核实（疑似就是标反前的读写教程3），已移除：
    # 未收录的 cid 一律走普通识别（页面标题/整页文字），不硬猜。
}


def book_of(url: str) -> str:
    """从页面 URL 里取出 cid 对应的教材名；取不到返回空串。"""
    if not url:
        return ""
    m = re.search(r"[?&]cid=([0-9]+)", url)
    return COURSE_MAP.get(m.group(1), "") if m else ""
